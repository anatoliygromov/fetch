"""tools/qa_triage.py QA.json OUT.md: the defect list from tools/asset_qa.py, sorted into what to do next.

  fix free     a script fixes it at 0 credits: noise/stray (tools/cleanpass.py), outline gaps
               (tools/outline_complete.py), specks and pinholes (a pixel patch), blotches (cleanpass, wider),
               uneven windows (stamp one clean window into every opening)
               (to build: blotch cleanup = cleanpass on 2-24 px patches; window stamping), colours (palette merge),
               ladder (a fade or shader value in code), flicker (a pixel patch)
  redraw       the drawing itself is wrong: wrong slot size, a sheet that is not whole frames; hand-pixel or
               regenerate (credits only after a brief is approved)
  rejected     batch 1: replaced by the gated pipeline, not fixed
"""
import sys, json
from collections import defaultdict
FREE = {"noise", "stray", "outline", "specks", "pinholes", "blotches", "windows", "alpha", "decor-ink"}
REDRAW = {"slot"}
d = json.load(open(sys.argv[1]))
rows = defaultdict(list)
for a in d:
    fails = [c for c in a["checks"] if c["sev"] == "fail"]
    warns = [c for c in a["checks"] if c["sev"] == "warn"]
    g = a.get("group", "")
    if a["verdict"] == "PASS": bucket = "pass"
    elif "Batch 1" in g: bucket = "rejected"
    elif any(c["id"] in REDRAW or "not a whole number" in c["msg"] for c in fails): bucket = "redraw"
    elif fails: bucket = "free"
    else: bucket = "warn"
    rows[bucket].append((g, a, fails, warns))
def line(g, a, fs, ws):
    ids = ", ".join(sorted({c["id"] for c in fs})) or "-"
    wid = ", ".join(sorted({c["id"] for c in ws})) or "-"
    return f"| {a['name']} | {g} | {a['layer']} | {ids} | {wid} |"
out = ["# Asset QA triage", "", f"Generated by tools/qa_triage.py from tools/asset_qa.py --all ({len(d)} assets). "
       "Cards: tools/qa_card.py. What each check means: docs/asset_qa.md.", ""]
names = {"free": "Fix free (scripts, 0 credits)", "redraw": "Redraw (hand-pixel, or credits after an approved brief)",
         "warn": "Pass with warnings (look at the card)", "rejected": "Batch 1 (rejected; for reference only)", "pass": "Pass"}
for b in ("free", "redraw", "warn", "rejected", "pass"):
    rs = sorted(rows[b], key=lambda r: (r[0], r[1]["name"]))
    out += [f"## {names[b]}: {len(rs)}", "", "| Asset | Group | Layer | Fails | Warnings |", "| --- | --- | --- | --- | --- |"]
    out += [line(*r) for r in rs] + [""]
open(sys.argv[2], "w").write("\n".join(out))
print({b: len(v) for b, v in rows.items()})
