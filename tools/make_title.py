# Builds the animated title screen from the title painting (source_title/title_original.png).
#   1. Down to the game's 320x240: each game pixel takes the median colour of the middle half of its cell
#      (the painting is pixel art at about 7.5 source px per game px, but not on an exact grid).
#   2. Clean-up: a 64-colour palette (k-means in Lab), then despeckle: a stray pixel takes the colour around it
#      when that colour is close (letters, outlines and highlights survive).
#   2b. Real pixels: tools/title_pixel.py redraws that cut by pixel-art rules (see there).
#   3. Layers for the animation, written to riverwalk/art/title/ and riverwalk/title_data.lua:
#      base.png       the screen with the river sparkles and the bird taken out (they are drawn live)
#      press_off.png  the "PRESS ANY KEY" box without its text (the text blinks)
#      eye_closed.png Pepper's open eye closed, drawn like her winking eye (she blinks)
#      bird.png       the bird: its own frame plus two wing positions (it flaps)
#      logo_hi.png    the logo letters brightened (a shine sweeps across them)
import os, numpy as np
from PIL import Image
from skimage.color import rgb2lab
from sklearn.cluster import KMeans
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'riverwalk', 'art', 'title')
os.makedirs(OUT, exist_ok=True)
W, H = 320, 240
src = np.array(Image.open(os.path.join(ROOT, 'source_title', 'title_original.png')).convert('RGB'))
h, w = src.shape[:2]
med = np.zeros((H, W, 3), np.uint8)
for j in range(H):
    y0 = int((j + 0.25) * h / H); y1 = max(y0 + 1, int((j + 0.75) * h / H))
    for i in range(W):
        x0 = int((i + 0.25) * w / W); x1 = max(x0 + 1, int((i + 0.75) * w / W))
        med[j, i] = np.median(src[y0:y1, x0:x1].reshape(-1, 3), axis=0)

# ---- 2. palette and despeckle
lab = rgb2lab(med / 255.0)
km = KMeans(n_clusters=64, n_init=4, random_state=1).fit(lab.reshape(-1, 3))
idx = km.labels_.reshape(H, W)
pal = np.array([med.reshape(-1, 3)[km.labels_ == k].mean(0) for k in range(64)]).round().astype(np.uint8)
for _ in range(2):
    out = idx.copy()
    for y in range(H):
        for x in range(W):
            c = idx[y, x]
            nb = [idx[yy, xx] for yy in range(max(0, y - 1), min(H, y + 2)) for xx in range(max(0, x - 1), min(W, x + 2)) if (yy, xx) != (y, x)]
            if sum(1 for n in nb if n == c) <= 1:
                vals, cnt = np.unique(nb, return_counts=True)
                m = vals[np.argmax(cnt)]
                if cnt.max() >= 5 and np.linalg.norm(lab[y, x] - km.cluster_centers_[m]) < 34:
                    out[y, x] = m
    idx = out
img = pal[idx].astype(int)
# ---- 2b. real pixels (22 Oct): the cut above still had the painting's AI texture. tools/title_pixel.py redraws
#      it by pixel-art rules (flat clusters, 30 colours on the VGA grid, sel-out outlines, a rebuilt logo, crisp boxes)
import sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from title_pixel import repixel
img = repixel(src, img.astype(np.uint8))
base = img.copy()
L = 0.3 * img[..., 0] + 0.59 * img[..., 1] + 0.11 * img[..., 2]

def save(a, name, alpha=None):
    a = np.clip(a, 0, 255).astype(np.uint8)
    if alpha is None: Image.fromarray(a, 'RGB').save(os.path.join(OUT, name))
    else: Image.fromarray(np.dstack([a, alpha.astype(np.uint8)]), 'RGBA').save(os.path.join(OUT, name))

lua = ['-- generated by tools/make_title.py: positions of the animated parts of the title screen', 'return {']

# ---- river sparkles: light pixels on water, grouped into horizontal streaks; taken out of the base
r, g, b = img[..., 0], img[..., 1], img[..., 2]
water = (b > r + 50) & (b > g + 10) & (L > 60) & (L < 175)
spark = np.zeros((H, W), bool)
for y in range(140, 200):
    for x in range(118, W):
        if L[y, x] > 175 and water[max(0, y - 1):y + 2, max(0, x - 1):x + 2].sum() >= 5: spark[y, x] = True
runs = []
for y in range(H):
    x = 0
    while x < W:
        if spark[y, x]:
            x0 = x
            while x < W and spark[y, x]: x += 1
            runs.append((x0, y, x - x0, tuple(int(v) for v in img[y, x0])))
        else: x += 1
for x0, y, n, _ in runs:                                   # fill with the water colour next to the streak
    left = img[y, x0 - 1] if x0 > 0 else img[y, x0 + n]
    right = img[y, x0 + n] if x0 + n < W else left
    for x in range(x0, x0 + n): base[y, x] = left if x - x0 < n / 2 else right
lua.append('  sparkles = {')
for x0, y, n, c in runs: lua.append('    { %d, %d, %d, %d, %d, %d },' % (x0, y, n, c[0], c[1], c[2]))
lua.append('  },')

# ---- the bird (x 248-270, y 100-114): its pixels are darker than the sky around it
bx0, by0, bx1, by1 = 248, 100, 270, 114
sky_L = np.median(L[by0:by1, bx0:bx1])
bird = np.zeros((H, W), bool); bird[by0:by1, bx0:bx1] = L[by0:by1, bx0:bx1] < sky_L - 8
ys, xs = np.nonzero(bird)
for y, x in zip(ys, xs):                                   # sky behind: nearest non-bird pixel in the same row
    for d in range(1, 20):
        if x - d >= 0 and not bird[y, x - d]: base[y, x] = img[y, x - d]; break
        if x + d < W and not bird[y, x + d]: base[y, x] = img[y, x + d]; break
fw, fh = bx1 - bx0, by1 - by0
frames = np.zeros((fh, fw * 3, 4), np.uint8)
tipy = int(ys.max())                                       # the point of the V (the body)
# frame 0: the bird as painted (wings up). Frame 1: the same pixels squashed towards the body (wings level).
# Frame 2: flipped below the body (wings down). Darker pixels win where two land on the same spot.
for fr, k in ((0, 1.0), (1, 0.3), (2, -0.45)):
    order = np.argsort(-L[ys, xs])                          # light first, dark last
    for i in order:
        y, x = ys[i], xs[i]
        ny = tipy - int(round((tipy - y) * k))
        if 0 <= ny - by0 < fh:
            frames[ny - by0, fr * fw + x - bx0, :3] = img[y, x]; frames[ny - by0, fr * fw + x - bx0, 3] = 255
Image.fromarray(frames, 'RGBA').save(os.path.join(OUT, 'bird.png'))
lua.append('  bird = { x = %d, y = %d, w = %d, h = %d },' % (bx0, by0, fw, fh))

# ---- Pepper's open eye, closed (centre 114.5, 108): fur from beside the eye, and a lid line like her wink
ex0, ey0, ex1, ey1 = 105, 97, 125, 120
cx, cy, rx, ry = 114.5, 108.0, 7.2, 9.7
patch = img[ey0:ey1, ex0:ex1].copy(); alpha = np.zeros(patch.shape[:2]); 
inside = lambda x, y: ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1
for y in range(ey0, ey1):
    for x in range(ex0, ex1):
        if inside(x, y):
            d = 1
            while inside(x - d, y) and inside(x + d, y): d += 1
            src_x = x - d if not inside(x - d, y) else x + d
            patch[y - ey0, x - ex0] = img[y, src_x]; alpha[y - ey0, x - ex0] = 255
lid = img[118:126, 66:92].reshape(-1, 3); lid = lid[np.argsort(lid.sum(1))][0]   # the wink's darkest colour
for x in range(108, 122):                                   # a gentle downward curve, 2 px thick
    t = (x - 108) / 13.0
    y = int(round(110 + 2.2 * (1 - (2 * t - 1) ** 2)))
    for yy in (y, y + 1):
        patch[yy - ey0, x - ex0] = lid; alpha[yy - ey0, x - ex0] = 255
save(patch, 'eye_closed.png', alpha)
lua.append('  eye = { x = %d, y = %d },' % (ex0, ey0))

# ---- "PRESS ANY KEY TO START": the box without its text
px0, py0, px1, py1 = 156, 189, 270, 205
box = img[py0:py1, px0:px1]
vals, cnt = np.unique(box.reshape(-1, 3), axis=0, return_counts=True); navy = vals[np.argmax(cnt)]
off = box.copy()
off[3:-3, 3:-3] = navy                                     # the whole inside, leaving the box's border
save(off, 'press_off.png')
lua.append('  press = { x = %d, y = %d },' % (px0, py0))

# ---- the logo letters, brightened (orange and yellow pixels in the logo's box)
lx0, ly0, lx1, ly1 = 118, 10, 304, 84
reg = img[ly0:ly1, lx0:lx1]
warm = (reg[..., 0] > 180) & (reg[..., 1] > 80) & (reg[..., 2] < 130)
hi = reg + (np.array([255, 248, 214]) - reg) * 0.6
save(hi, 'logo_hi.png', warm * 255)
lua.append('  logo = { x = %d, y = %d, w = %d, h = %d },' % (lx0, ly0, lx1 - lx0, ly1 - ly0))

# ---- the two lamps (centre of each lantern)
lua.append('  lamps = { { 34, 63, 9 }, { 287, 135, 4 } },')
save(base, 'base.png')
lua.append('}')
open(os.path.join(ROOT, 'riverwalk', 'title_data.lua'), 'w').write('\n'.join(lua) + '\n')
print('sparkle streaks', len(runs), 'bird pixels', len(ys), 'navy', navy, 'logo pixels', int(warm.sum()))
