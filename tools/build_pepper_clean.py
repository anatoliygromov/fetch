# CLEAN build: every row is one whole SpriteCook clip in order, then cleaned (tools/clean.py:
# palette snap, specks removed, white eye, 1 px outline where the edge had none). Cells are 60x52:
# 52 px clips get 4 px of empty space each side, 60 px clips lose their top 8 rows (always empty; checked).
# One anchor per clip: x = cell centre, y = the clip's own ground line (lowest paw row + 1), so the
# dog sits in each frame exactly where SpriteCook drew her.
import numpy as np, collections, sys
import os
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from clean import clean_pepper_row
from PIL import Image
SH=os.path.join(ROOT,'source_sheets'); OUT=os.path.join(ROOT,'riverwalk')
CW, CH = 60, 52
def clip(name):
    a=np.array(Image.open(f'{SH}/{name}.png').convert('RGBA')); h=a.shape[0]
    raw=[]
    for i in range(a.shape[1]//h):
        f=a[:,i*h:(i+1)*h]
        if h==52: g=np.zeros((60,60,4),np.uint8); g[8:,4:56]=f
        else: g=f
        raw.append(g)
    cl,rep=clean_pepper_row(raw, **OPTS.get(name,{}))
    REPORT[name]=rep
    out=[]
    for g in cl:
        assert not g[:8,:,3].any(), name+' has pixels in the cropped rows'
        out.append(g[8:])
    return out
OPTS={'pepper_idle':dict(no_eye=(5,))}
REPORT={}
ROWS=collections.OrderedDict([
  ('idle','pepper_idle'), ('happy','pepper_happy'), ('wag','pepper_tail_wag'), ('walk','pepper_walk'),
  ('run','pepper_gallop_a'), ('jump','pepper_jump_v15'), ('skid','pepper_skid_v15'), ('crouch','pepper_crouch_new'),
  ('crawl','pepper_crawl_v15'), ('hurt','pepper_hurt_new'), ('sit','pepper_sit'), ('bark','pepper_bark'),
  ('sniff','pepper_sniff'), ('grab','pepper_pickup_v15')])
F={k:clip(v) for k,v in ROWS.items()}
# hand fixes after the automatic cleanup, cell coordinates (x, y), 1-based frame numbers
from clean import PAL, EYE, BODY
MANUAL={
  ('hurt',3): [('erase', 49, 25, 51, 28),                 # drool hanging from the mouth
               ('px', 39, 12, BODY), ('px', 45, 15, EYE)], # eye sat on the ear; move it into the eye socket
}
for (name,fn),ops in MANUAL.items():
    f=F[name][fn-1]
    for op in ops:
        if op[0]=='erase': f[op[2]:op[4]+1, op[1]:op[3]+1]=0
        else:
            _,x,y,c=op; f[y,x,:3]=PAL[c]; f[y,x,3]=255
W=max(len(f) for f in F.values())*CW
sheet=np.zeros((len(F)*CH,W,4),np.uint8)
lua=['-- generated by tools/build_pepper_clean.py: whole SpriteCook clips, cleaned, cells 60x52','return {','  CW = 60, CH = 52,','  rows = {']
for r,(name,fr) in enumerate(F.items()):
    bots=[int(np.nonzero(a[:,:,3].any(1))[0].max()) for a in fr]
    g=max(bots)+1
    ents=[]
    for c,a in enumerate(fr):
        sheet[r*CH:(r+1)*CH,c*CW:(c+1)*CW]=a
        al=a[:,:,3]>0; ys=np.nonzero(al.any(1))[0]; top=ys.min()
        mx,my=-1,top
        for y in range(top,bots[c]-7):
            xs=np.nonzero(al[y])[0]
            if len(xs) and xs.max()>mx: mx,my=xs.max(),y
        ents.append('{ x = 30, y = %d, mx = %d, my = %d }'%(g,mx-30,my+3-g))
    lua.append('    { name = "%s", src = "%s", n = %d, f = { %s } },'%(name,ROWS[name],len(fr),', '.join(ents)))
lua+=['  },','}']
Image.fromarray(sheet,'RGBA').save(f'{OUT}/art/pepper.png')
open(f'{OUT}/pepper_frames.lua','w').write('\n'.join(lua)+'\n')
# proof that pixels are untouched: every frame in the sheet equals its source frame
[print(k,[r for r in v if r[1] is None or (isinstance(r[1],tuple) and r[1][0]=='copied')]) for k,v in REPORT.items()]
print('rows', {k:len(v) for k,v in F.items()}, 'sheet', sheet.shape)
