# Builds the river layer from the SpriteCook water strip (source_scenery/water_strip_spritecook.png, 320x94,
# asset d19d28b6-604b-4b55-815f-635a5e532f86):
#   * rows 0-23 are haze above the waterline and are dropped; the water rows 24-93 are kept, and its deepest
#     rows (86-93) are repeated to reach the bottom of the screen: 94 rows, drawn from y 146 to 240
#   * clean-up: 20-colour palette (k-means in Lab) and despeckle, as for the title
#   * the white glints are taken out into riverwalk/water_data.lua and drawn live, so they can twinkle
import os, numpy as np
from PIL import Image
from skimage.color import rgb2lab
from sklearn.cluster import KMeans
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = np.array(Image.open(os.path.join(ROOT, 'source_scenery', 'water_strip_spritecook.png')).convert('RGB'))
rows = list(range(24, 94)) + [86 + (i % 8) for i in range(24)]
img = src[rows].copy()
H, W = img.shape[:2]
lab = rgb2lab(img / 255.0)
km = KMeans(n_clusters=20, n_init=4, random_state=1).fit(lab.reshape(-1, 3))
idx = km.labels_.reshape(H, W)
pal = np.array([img.reshape(-1, 3)[km.labels_ == k].mean(0) for k in range(20)]).round().astype(np.uint8)
for _ in range(2):
    out = idx.copy()
    for y in range(H):
        for x in range(W):
            c = idx[y, x]
            nb = [idx[yy, (xx) % W] for yy in range(max(0, y - 1), min(H, y + 2)) for xx in range(x - 1, x + 2) if (yy, xx) != (y, x)]
            if sum(1 for n in nb if n == c) <= 1:
                vals, cnt = np.unique(nb, return_counts=True)
                m = vals[np.argmax(cnt)]
                if cnt.max() >= 5 and np.linalg.norm(lab[y, x] - km.cluster_centers_[m]) < 18: out[y, x] = m
    idx = out
img = pal[idx].astype(int)
L = 0.3 * img[..., 0] + 0.59 * img[..., 1] + 0.11 * img[..., 2]
# glints: pixels much lighter than the water row they sit in (white stars and bright streaks)
rowL = np.median(L, axis=1)
glint = L > rowL[:, None] + 45
lua = ['-- generated by tools/make_water.py: the river\'s glints { x, y, length, r, g, b }', 'return {']
base = img.copy()
for y in range(H):
    x = 0
    while x < W:
        if glint[y, x]:
            x0 = x
            while x < W and glint[y, x]: x += 1
            c = img[y, x0]
            lua.append('  { %d, %d, %d, %d, %d, %d },' % (x0, y, x - x0, c[0], c[1], c[2]))
            fill = img[y, x0 - 1] if x0 > 0 else img[y, x % W]
            base[y, x0:x] = fill
        else: x += 1
lua.append('}')
Image.fromarray(base.astype(np.uint8)).save(os.path.join(ROOT, 'riverwalk', 'art', 'scene', 'water.png'))
open(os.path.join(ROOT, 'riverwalk', 'water_data.lua'), 'w').write('\n'.join(lua) + '\n')
print('water', W, H, 'glints', len(lua) - 3, 'colours', len(np.unique(idx)))
