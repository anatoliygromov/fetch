# Cleaned (palette snap, specks, outline) then builds rw2/art/girl.png (66x66 cells, one row per animation) and rw2/girl_frames.lua from the side-view SpriteCook sheets.
import numpy as np, collections, sys
import os
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from clean import clean_girl_row, girl_palette
from PIL import Image
SH=os.path.join(ROOT,'source_sheets'); OUT=os.path.join(ROOT,'riverwalk'); C=66
PAL=girl_palette()
def frames(n):
    a=np.array(Image.open(f'{SH}/{n}.png').convert('RGBA')); h=a.shape[0]
    fr=[]
    for i in range(a.shape[1]//h):
        f=a[:,i*h:(i+1)*h]
        if h>C:                                   # bigger cells from the precise engine: keep the bottom 66 rows, centred
            o=(h-C)//2
            assert not f[:h-C,:,3].any() and not f[:,:o,3].any() and not f[:,o+C:,3].any(), n+': pixels outside the 66 px crop'
            f=f[h-C:,o:o+C]
        fr.append(f)
    return clean_girl_row(fr, PAL)
ROWS=collections.OrderedDict([('idle',frames('girl_stand_idle')),('wave',frames('girl_stand_wave')),
     ('cheer',frames('girl_stand_cheer')),('call',frames('girl_stand_call')),('pet',frames('girl_stand_pet'))])
W=max(len(f) for f in ROWS.values())*C
sheet=np.zeros((len(ROWS)*C,W,4),np.uint8)
lua=['-- generated by tools/build_girl.py: cells 66x66, one row per animation; x, y = anchor (feet centre)','return {','  CW = 66, CH = 66,','  rows = {']
# one shared x anchor: the mean centre of the idle frames, so switching animations never shifts her sideways
xs=[]
for a in ROWS['idle']:  # anchor from the standing idle
    cols=np.nonzero(a[:,:,3].any(0))[0]; xs.append((cols.min()+cols.max()+1)/2)
ax=int(round(sum(xs)/len(xs)))
for r,(name,fr) in enumerate(ROWS.items()):
    bots=[int(np.nonzero(a[:,:,3].any(1))[0].max()) for a in fr]
    g=collections.Counter(bots).most_common(1)[0][0]+1
    for c,a in enumerate(fr): sheet[r*C:(r+1)*C,c*C:(c+1)*C]=a
    lua.append('    { name = "%s", n = %d, x = %d, y = %d },'%(name,len(fr),ax,g))
lua+=['  },','}']
Image.fromarray(sheet,'RGBA').save(f'{OUT}/art/girl.png')
open(f'{OUT}/girl_frames.lua','w').write('\n'.join(lua)+'\n')
print(open(f'{OUT}/girl_frames.lua').read())
