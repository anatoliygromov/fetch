local order = ""
for k in pairs(G) do order = order .. k end

local data = love.image.newImageData(1 + #order * 6, 7)
for i = 1, #order do
  local x0 = (i - 1) * 6
  for y = 0, 6 do data:setPixel(x0, y, 1, 0, 1, 1) end
  local rows = G[order:sub(i, i)]
  for y = 1, 7 do
    for x = 1, 5 do
      if rows[y]:sub(x, x) == "#" then data:setPixel(x0 + x, y - 1, 1, 1, 1, 1) end
    end
  end
end
for y = 0, 6 do data:setPixel(#order * 6, y, 1, 0, 1, 1) end

F.font = love.graphics.newImageFont(data, order, 1)
F.font:setFilter("nearest", "nearest")

-- letters are all capitals; a small "x" is the times sign (x3)
local function caps(text) return (text:gsub("[a-wyz]", string.upper)) end

function F.width(text, scale)
  return F.font:getWidth(caps(text)) * (scale or 2) - (scale or 2)
end

-- draw text in the current colour at a whole-pixel position
function F.print(text, x, y, scale)
  local old = love.graphics.getFont()
  love.graphics.setFont(F.font)
  love.graphics.print(caps(text), math.floor(x + 0.5), math.floor(y + 0.5), 0, scale or 2, scale or 2)
  love.graphics.setFont(old)
end

-- centred on x
function F.center(text, x, y, scale)
  F.print(text, x - F.width(text, scale) / 2, y, scale)
end

return F
