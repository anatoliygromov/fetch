"""Builds the title screen (v2, 24 Oct) from the painting and the owner's Artlist videos:
    python3 art/source/title/tools/build_title.py          (from the repo root; about a minute)
  1. Native pixels: the painting (source_title/title_original.png, 2400 x 1792) sampled one colour per cell on its
     7.5 px grid, the sample window registered to the drawn pixel inside each cell (title_native.py). 320 x 239,
     the last row repeated once to fill 240 (a whole-pixel pad). Cached in art/source/title/native.png.
  2. Palette: 62 colours, k-means in Lab in two groups so Pepper's black coat keeps its sheen ramp and the bandana
     its pinks (title_palette.py); nearest colour, then lone pixels that are only a shade off take their
     neighbours' colour. No dithering.
  3. The painting's PRESS ANY KEY TO START box taken out, the railing behind it rebuilt from the painting's own
     rows (unbox.py); the game draws PRESS START itself.
  4. Layers for the animation (riverwalk/art/title/, positions in riverwalk/title_data.lua):
       base.png     the screen without the river sparkles and the bird (drawn live)
       bird.png     the bird: as painted, wings level, wings down
       logo_hi.png  the logo letters brightened (the shine)
       mouth.png    Pepper's pant: her mouth region in 3 frames (the still, tongue half down, tongue down), the
                    tongue's outline from the video t2 (frames 18 and 21, registered on her head), its pixels the
                    still's (head_frames.pant)
       eye.png      her blink: the open eye in 3 frames (the still, half shut, shut), drawn on the still's pixels
     Every frame of mouth.png and eye.png is the still outside the pixels that change (checked here).
"""
import os, sys, json
import numpy as np
import cv2
from PIL import Image
from skimage.color import rgb2lab
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import title_native, title_palette as TP, unbox, head_frames as HF
from register import register
from vsample import sample as vsample
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..', '..'))
SRC = os.path.join(ROOT, 'source_title', 'title_original.png')
TDIR = os.path.join(ROOT, 'art', 'source', 'title')
OUT = os.path.join(ROOT, 'riverwalk', 'art', 'title')
W, H = 320, 240

def save(a, name, alpha=None):
    a = np.clip(a, 0, 255).astype(np.uint8)
    if alpha is None: Image.fromarray(a, 'RGB').save(os.path.join(OUT, name))
    else: Image.fromarray(np.dstack([a, alpha.astype(np.uint8)]), 'RGBA').save(os.path.join(OUT, name))

def main():
    os.makedirs(OUT, exist_ok=True)
    # ---- 1. native pixels
    cache = os.path.join(TDIR, 'native.png')
    if os.path.exists(cache): nat = np.array(Image.open(cache).convert('RGB'))
    else:
        nat, pur = title_native.sample(np.array(Image.open(SRC).convert('RGB')), 0.0, 2.5)
        Image.fromarray(nat).save(cache); print('native', nat.shape, 'purity %.3f' % pur.mean())
    # ---- 2. palette
    pal = TP.build(nat.astype(float))
    idx = TP.apply(nat.astype(float), pal)
    idx = np.vstack([idx, idx[-1:]])                                  # 239 -> 240 rows
    lum = pal[idx].sum(2) // 3
    # ---- 3. the box out
    idx = unbox.unbox(idx, lum)
    img = pal[idx].astype(int)
    L = rgb2lab(pal[idx] / 255.0)[..., 0]
    pstrip = np.repeat(np.repeat(pal[None], 8, 0), 8, 1); Image.fromarray(pstrip.astype(np.uint8)).save(os.path.join(TDIR, 'palette.png'))
    still = img.copy()
    base = img.copy()
    lua = ['-- generated by art/source/title/tools/build_title.py: positions of the animated parts of the title screen', 'return {']
    Lum = 0.3 * img[..., 0] + 0.59 * img[..., 1] + 0.11 * img[..., 2]
    # ---- river sparkles: light pixels on the water, in horizontal streaks; taken out of the base
    r, g, b = img[..., 0], img[..., 1], img[..., 2]
    water = (b > r + 50) & (b > g + 10) & (Lum > 60) & (Lum < 175)
    spark = np.zeros((H, W), bool)
    for y in range(140, 188):
        for x in range(130, W):
            if Lum[y, x] > 175 and water[max(0, y - 1):y + 2, max(0, x - 1):x + 2].sum() >= 5: spark[y, x] = True
    runs = []
    for y in range(H):
        x = 0
        while x < W:
            if spark[y, x]:
                x0 = x
                while x < W and spark[y, x]: x += 1
                runs.append((x0, y, x - x0, tuple(int(v) for v in img[y, x0])))
            else: x += 1
    for x0, y, n, _ in runs:
        left = img[y, x0 - 1]; right = img[y, x0 + n] if x0 + n < W else left
        for x in range(x0, x0 + n): base[y, x] = left if x - x0 < n / 2 else right
    lua.append('  sparkles = {')
    for x0, y, n, c in runs: lua.append('    { %d, %d, %d, %d, %d, %d },' % (x0, y, n, c[0], c[1], c[2]))
    lua.append('  },')
    # ---- the bird (x 250-270, y 100-112): darker than the sky round it
    bx0, by0, bx1, by1 = 249, 100, 271, 113
    sky_L = np.median(Lum[by0:by1, bx0:bx1])
    bird = np.zeros((H, W), bool); bird[by0:by1, bx0:bx1] = Lum[by0:by1, bx0:bx1] < sky_L - 8
    ys, xs = np.nonzero(bird); nbird = len(ys)
    for y, x in zip(ys, xs):
        for d in range(1, 20):
            if not bird[y, x - d]: base[y, x] = img[y, x - d]; break
            if not bird[y, x + d]: base[y, x] = img[y, x + d]; break
    fw, fh = bx1 - bx0, by1 - by0
    frames = np.zeros((fh, fw * 3, 4), np.uint8)
    tipy = int(ys.max())
    for fr, k in ((0, 1.0), (1, 0.3), (2, -0.45)):
        for i in np.argsort(-Lum[ys, xs]):
            y, x = ys[i], xs[i]; ny = tipy - int(round((tipy - y) * k))
            if 0 <= ny - by0 < fh: frames[ny - by0, fr * fw + x - bx0, :3] = img[y, x]; frames[ny - by0, fr * fw + x - bx0, 3] = 255
    Image.fromarray(frames, 'RGBA').save(os.path.join(OUT, 'bird.png'))
    lua.append('  bird = { x = %d, y = %d, w = %d, h = %d },' % (bx0, by0, fw, fh))
    # ---- the logo letters, brightened (orange and yellow pixels in the logo's box)
    lx0, ly0, lx1, ly1 = 118, 10, 304, 84
    reg = img[ly0:ly1, lx0:lx1]
    warm = (reg[..., 0] > 180) & (reg[..., 1] > 80) & (reg[..., 2] < 130)
    hi = reg + (np.array([255, 248, 214]) - reg) * 0.6
    save(hi, 'logo_hi.png', warm * 255)
    lua.append('  logo = { x = %d, y = %d, w = %d, h = %d },' % (lx0, ly0, lx1 - lx0, ly1 - ly0))
    # ---- Pepper: the pant (from the video) and the blink (drawn on the still)
    BX, BY, BW, BH = 10, 75, 150, 161
    cap = cv2.VideoCapture(os.path.join(TDIR, 'video', 't2.mp4')); vf = {}
    for k in range(25):
        ok, f = cap.read()
        if k in (0, 18, 21): vf[k] = f
    reg0 = None; vs = {}
    for k in (0, 18, 21):
        r0 = register(still.astype(np.uint8), vf[k], near=reg0, scales=np.arange(3.38, 3.52, 0.01) if reg0 is None else np.arange(reg0[0] - 0.02, reg0[0] + 0.021, 0.01))
        reg0 = r0; vs[k] = vsample(vf[k], r0[0], r0[1], r0[2], (BX, BY, BX + BW, BY + BH)); print('t2 frame', k, 'registered: scale %.2f at %.1f, %.1f, ncc %.2f' % r0)
    crop_idx = idx[BY:BY + BH, BX:BX + BW]; crop_rgb = still[BY:BY + BH, BX:BX + BW].astype(float)
    mouth = [idx.copy()]
    for k in (18, 21):
        o, m = HF.pant(crop_idx, crop_rgb, vs[k]); f = idx.copy(); f[BY:BY + BH, BX:BX + BW] = o; mouth.append(f)
    ink, fur = idx[104, 110], idx[110, 104]
    arc = [(108, 106), (109, 107), (110, 108), (111, 108), (112, 109), (113, 109), (114, 109), (115, 109), (116, 108), (117, 108), (118, 107), (119, 106)]
    closed, _ = HF.blink(idx, L, range(99, 118), arc + [(x, y + 1) for x, y in arc[3:-3]], ink, fur)
    half, _ = HF.blink(idx, L, range(99, 107), [(x, 108) for x in range(108, 120)] + [(x, 107) for x in range(110, 118)], ink, fur)
    eye = [idx.copy(), half, closed]
    for name, fr in (('mouth', mouth), ('eye', eye)):
        ch = np.zeros((H, W), bool)
        for f in fr[1:]: ch |= f != idx
        ys, xs = np.nonzero(ch); x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
        strip = np.concatenate([pal[f[y0:y1, x0:x1]] for f in fr], axis=1)
        for f in fr: assert (f[~ch] == idx[~ch]).all()                 # the still outside the changing pixels
        Image.fromarray(strip.astype(np.uint8)).save(os.path.join(OUT, name + '.png'))
        lua.append('  %s = { x = %d, y = %d, w = %d, h = %d, n = %d },' % (name, x0, y0, x1 - x0, y1 - y0, len(fr)))
        print(name, 'frames', len(fr), 'region', x0, y0, x1 - x0, y1 - y0, 'changed px', int(ch.sum()))
    save(base, 'base.png')
    lua.append('}')
    open(os.path.join(ROOT, 'riverwalk', 'title_data.lua'), 'w').write('\n'.join(lua) + '\n')
    print('palette', len(pal), 'colours; base colours', len(np.unique(base.reshape(-1, 3), axis=0)), '; sparkle streaks', len(runs), '; bird px', nbird)

if __name__ == "__main__":
    main()
