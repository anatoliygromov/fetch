ROWS = 9
SPACE = 4          # space width; with the 1 px gaps on both sides a word gap is 6 px, as painted
GAP = 1


def glyph(ch):
    if ch in RECOVERED:
        return RECOVERED[ch]
    return DRAWN[ch]


def width(ch):
    return SPACE if ch == ' ' else len(glyph(ch)[1][0])


def text_width(s):
    g = layout(s, 0)
    return g[-1][1] + width(g[-1][0]) if g else 0


def layout(s, x0=0):
    """Returns [(ch, x)] for every non-space glyph, letter gap 1 px, word gap SPACE + 2."""
    out, x, prev = [], x0, None
    for ch in s:
        if ch == ' ':
            x += GAP + SPACE + GAP if prev not in (None, ' ') else 0
            prev = ch
            continue
        if prev not in (None, ' '):
            x += GAP
        out.append((ch, x))
        x += width(ch)
        prev = ch
    return out


def stamp(mask, s, x0, cap_row):
    """Draw string s into a boolean mask; cap_row is the output row of glyph row 0."""
    for ch, x in layout(s, x0):
        top, rows = glyph(ch)
        for r, line in enumerate(rows):
            for c, v in enumerate(line):
                if v == '#':
                    mask[cap_row + top + r, x + c] = True
    return mask
